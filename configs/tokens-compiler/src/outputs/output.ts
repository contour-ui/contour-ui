/**
 * An output turns the model into files of the package: entries (TypeScript modules that tsdown
 * builds into `.js` and `.d.ts`) and assets (files emitted as they are).
 */
import path from 'node:path';

import type { Tier, TokenModel } from '../model/model.ts';
import type { Report } from '../model/problem.ts';

export type Artifact =
  | {
      readonly kind: 'entry';
      /** The entry of the package: `dist/<name>.js`. */
      readonly name: string;
      readonly code: string;
    }
  | { readonly kind: 'asset'; readonly fileName: string; readonly source: string };

export interface TokenOutput {
  readonly name: string;
  /** The entries it adds to the package, known before the build: tsdown takes them first. */
  readonly entries: readonly string[];
  build(model: TokenModel, report: Report): readonly Artifact[];
}

export interface TierOption {
  /** The tiers of tokens the output takes. */
  readonly tiers?: readonly Tier[];
}

/** The first line of every generated file. */
export const generatedBy = (model: TokenModel): string =>
  `Generated by @contour-ui/tokens-compiler from ${path.basename(model.resolver)}. Do not edit.`;

/** A key of a TypeScript object literal: an identifier as it is, anything else quoted. */
export const propertyName = (key: string): string =>
  /^[A-Za-z_$][\w$]*$/u.test(key) ? key : `'${key}'`;

/** A doc comment on one line. */
export const docComment = (pad: string, text: string): string =>
  `${pad}/** ${text.replaceAll('*/', String.raw`*\/`)} */`;
