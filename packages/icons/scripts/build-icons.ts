/** `chevron-right` -> `chevronRightIcon`. */
export function exportName(name: string): string {
  const camel = name.replaceAll(/-([\da-z])/gu, (_match, letter: string) => letter.toUpperCase());
  const identifier = `${camel}Icon`;
  if (!/^[a-z][\dA-Za-z]*$/u.test(identifier) || RESERVED_EXPORTS.has(identifier)) {
    throw new Error(`"${name}" does not make a usable export name (${identifier}).`);
  }
  return identifier;
}

interface BuiltIcon {
  readonly exportName: string;
  readonly name: string;
  readonly description: string;
  readonly strokeWidth: number;
  readonly paths: ReadonlyArray<NormalizedPath & { readonly fill: boolean }>;
}

function buildIcon({ name, description, strokeWidth, paths }: SourceIcon): BuiltIcon {
  return {
    exportName: exportName(name),
    name,
    description,
    strokeWidth,
    paths: paths.map(({ d, fill }, index) => {
      const normalized = normalizePath(d, `${name}, path ${index}`);
      return { d: normalized.d, commands: normalized.commands, fill };
    }),
  };
}

function printIcon(icon: BuiltIcon): string {
  const paths = icon.paths.map(
    ({ d, commands, fill }) =>
      `    { d: '${d}', commands: [${commands.join(', ')}], fill: ${String(fill)} },`,
  );
  return [
    `/** ${icon.description.replaceAll('*/', String.raw`*\/`)} */`,
    `export const ${icon.exportName}: IconData = {`,
    `  name: '${icon.name}',`,
    `  size: ${GRID},`,
    `  strokeWidth: ${icon.strokeWidth},`,
    '  paths: [',
    ...paths,
    '  ],',
    '};',
  ].join('\n');
}

/** Build the source of `src/generated/icons.ts` in memory (used by the CLI and the freshness test). */
export function buildIcons(): string {
  const nodes = lucideNodes();
  const info = simpleIconInfo();
  const icons = [
    ...LUCIDE_ICONS.map((name) => lucideIcon(nodes, name)),
    ...SIMPLE_ICONS.map((slug) => simpleIcon(info, slug)),
  ].map((icon) => buildIcon(icon));

  const names = icons.map((icon) => icon.exportName);
  const duplicate = names.find((name, index) => names.indexOf(name) !== index);
  if (duplicate !== undefined) {
    throw new Error(`Two icons export ${duplicate}: drop one from scripts/icon-list.ts.`);
  }

  return [
    ...HEADER,
    '',
    "import type { IconData } from '../icon-data.ts';",
    '',
    // Sorted by export name (unique, see above), whatever the order of the list.
    icons
      .toSorted((a, b) => (a.exportName < b.exportName ? -1 : 1))
      .map((icon) => printIcon(icon))
      .join('\n\n'),
    '',
  ].join('\n');
}
