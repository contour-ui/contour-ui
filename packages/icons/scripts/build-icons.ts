/**
 * Build `src/generated/icons.ts` from `scripts/icon-list.ts`.
 *
 * - Lucide icons come from `lucide-static`: the shapes from `icon-nodes.json`, the
 *   grid and the stroke from the root `<svg>` of `icons/<name>.svg`.
 * - Brand logos come from `simple-icons`: one filled path per `icons/<slug>.svg`.
 *
 * Every shape becomes a normalized path (`path-data.ts`). The output depends only
 * on the icon list and the installed sources, so `src/generated.test.ts` compares
 * it with the committed file byte for byte.
 */
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

import { titleToSlug } from 'simple-icons/sdk';

import { LUCIDE_ICONS, SIMPLE_ICONS } from './icon-list.ts';
import { normalizePath, parseNumber, shapeToPath } from './path-data.ts';
import type { Attributes, NormalizedPath } from './path-data.ts';

export const PACKAGE_DIR = path.resolve(import.meta.dirname, '..');
export const ICONS_FILE = path.join(PACKAGE_DIR, 'src', 'generated', 'icons.ts');

const HEADER = [
  '// Generated by packages/icons/scripts/build.ts from scripts/icon-list.ts. Do not edit.',
  '// Icon data: Lucide (ISC, see README.md) and Simple Icons (CC0-1.0).',
];

/** Every icon is drawn on a `0 0 24 24` grid (checked against the sources). */
const GRID = 24;

/** Names exported by hand from `src/index.ts` that an icon export must not shadow. */
const RESERVED_EXPORTS: ReadonlySet<string> = new Set(['drawIcon']);

const packageRequire = createRequire(import.meta.url);

/** Text of a file inside an installed package (`lucide-static/icon-nodes.json`). */
const readPackageFile = (specifier: string): string =>
  readFileSync(packageRequire.resolve(specifier), 'utf8');

function readPackageJson(specifier: string): unknown {
  const parsed: unknown = JSON.parse(readPackageFile(specifier));
  return parsed;
}

function isRecord(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isAttributes(value: unknown): value is Attributes {
  return isRecord(value) && Object.values(value).every((item) => typeof item === 'string');
}

interface SourcePath {
  /** Path data as in the source: any commands, relative or absolute. */
  readonly d: string;
  readonly fill: boolean;
}

interface SourceIcon {
  readonly name: string;
  /** JSDoc of the export. */
  readonly description: string;
  readonly strokeWidth: number;
  readonly paths: readonly SourcePath[];
}

/** Attributes of the root `<svg>` element of an SVG file. */
function rootAttributes(svg: string, what: string): Attributes {
  const tag = /<svg\b([^>]*)>/u.exec(svg)?.[1];
  if (tag === undefined) {
    throw new Error(`${what}: no <svg> element.`);
  }
  return Object.fromEntries(
    [...tag.matchAll(/([\w:-]+)="([^"]*)"/gu)].map((match) => [match[1] ?? '', match[2] ?? '']),
  );
}

// ---------------------------------------------------------------------------
// Lucide
// ---------------------------------------------------------------------------

/** Root `<svg>` attributes every Lucide icon must have: the grid and the stroke style drawIcon assumes. */
const LUCIDE_ROOT: Attributes = {
  viewBox: `0 0 ${GRID} ${GRID}`,
  fill: 'none',
  stroke: 'currentColor',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
};

/** A node of `icon-nodes.json`: `[tag, attributes]`. */
function isNode(value: unknown): value is readonly [string, Attributes] {
  return (
    Array.isArray(value) &&
    value.length === 2 &&
    typeof value[0] === 'string' &&
    isAttributes(value[1])
  );
}

/** The shapes of every Lucide icon in `icon-nodes.json`, by current name (no aliases). */
export function lucideNodes(): Readonly<Record<string, unknown>> {
  const nodes = readPackageJson('lucide-static/icon-nodes.json');
  if (!isRecord(nodes)) {
    throw new TypeError('lucide-static/icon-nodes.json: expected an object.');
  }
  return nodes;
}

export function lucideIcon(nodes: Readonly<Record<string, unknown>>, name: string): SourceIcon {
  const what = `lucide-static "${name}"`;
  const elements = nodes[name];
  if (!Array.isArray(elements)) {
    throw new TypeError(
      `${what}: not in icon-nodes.json (renamed icons keep only their current name).`,
    );
  }

  const root = rootAttributes(readPackageFile(`lucide-static/icons/${name}.svg`), what);
  for (const [attribute, expected] of Object.entries(LUCIDE_ROOT)) {
    if (root[attribute] !== expected) {
      throw new Error(`${what}: expected ${attribute}="${expected}" on <svg>.`);
    }
  }
  const strokeWidth = parseNumber(root['stroke-width'] ?? '', `${what} stroke-width`);

  const paths = elements.flatMap((node: unknown, index): SourcePath[] => {
    const where = `${what}, node ${index}`;
    if (!isNode(node)) {
      throw new TypeError(`${where}: expected [tag, attributes].`);
    }
    const [tag, { fill = 'none', ...geometry }] = node;
    const d = shapeToPath(tag, geometry, where);
    switch (fill) {
      case 'none': {
        return [{ d, fill: false }];
      }
      case 'currentColor': {
        // A filled dot keeps the icon's stroke on top: fill first, then the same outline stroked.
        return [
          { d, fill: true },
          { d, fill: false },
        ];
      }
      default: {
        throw new Error(`${where}: fill="${fill}" is not supported.`);
      }
    }
  });

  return {
    name,
    description: `[\`${name}\`](https://lucide.dev/icons/${name}) from Lucide.`,
    strokeWidth,
    paths,
  };
}

// ---------------------------------------------------------------------------
// Simple Icons
// ---------------------------------------------------------------------------

interface SimpleIconInfo {
  readonly slug: string;
  readonly title: string;
  readonly guidelines: string | undefined;
  readonly license: string | undefined;
}

/** Title, brand guidelines and license of every Simple Icons logo, from its data file. */
function simpleIconInfo(): Map<string, SimpleIconInfo> {
  const data = readPackageJson('simple-icons/icons.json');
  if (!Array.isArray(data)) {
    throw new TypeError('simple-icons/icons.json: expected an array.');
  }
  const entries = data.map((entry: unknown): SimpleIconInfo => {
    if (!isRecord(entry) || typeof entry['title'] !== 'string') {
      throw new TypeError('simple-icons/icons.json: expected entries with a title.');
    }
    const { title, slug, guidelines, license } = entry;
    return {
      title,
      // The data omits the slug when it is derived from the title.
      slug: typeof slug === 'string' ? slug : titleToSlug(title),
      guidelines: typeof guidelines === 'string' ? guidelines : undefined,
      license:
        isRecord(license) && typeof license['type'] === 'string' ? license['type'] : undefined,
    };
  });
  return new Map(entries.map((info) => [info.slug, info]));
}

const SIMPLE_ICON_SVG = /^<svg [^>]*><title>[^<]*<\/title><path d="([^"]+)"\/><\/svg>\s*$/u;

function simpleIcon(info: ReadonlyMap<string, SimpleIconInfo>, slug: string): SourceIcon {
  const what = `simple-icons "${slug}"`;
  const icon = info.get(slug);
  if (icon === undefined) {
    throw new Error(`${what}: not in simple-icons/icons.json.`);
  }
  // Simple Icons itself is CC0, but a logo may carry its own license, which could
  // require a notice: add the notice before allowing it here.
  if (icon.license !== undefined && icon.license !== 'CC0-1.0') {
    throw new Error(`${what}: the logo is licensed ${icon.license}, which needs a notice.`);
  }

  const svg = readPackageFile(`simple-icons/icons/${slug}.svg`);
  const d = SIMPLE_ICON_SVG.exec(svg)?.[1];
  if (d === undefined || rootAttributes(svg, what)['viewBox'] !== `0 0 ${GRID} ${GRID}`) {
    throw new Error(`${what}: expected a single <path> on a 0 0 ${GRID} ${GRID} viewBox.`);
  }

  const guidelines = icon.guidelines === undefined ? '' : ` Brand guidelines: ${icon.guidelines}`;
  return {
    name: slug,
    description: `${icon.title} logo from Simple Icons (\`${slug}\`).${guidelines}`,
    // Logos are filled only.
    strokeWidth: 0,
    paths: [{ d, fill: true }],
  };
}

