/**
 * The tokens as Soundor styles take them, for the `@contour-ui/soundor` packages: one object of
 * values per theme in `src/generated/soundor.ts`. Soundor has no CSS, so nothing is a `var()`
 * reference: colors are hex (8 digits with an alpha), lengths and durations plain numbers (px,
 * ms), a curve the named easing closest to it, and a text style the style properties of a
 * Soundor `Text`. Shadows have no Soundor equivalent and are left out; base tokens stay internal,
 * as in `vars`.
 */
import { formatHex, formatHex8 } from 'culori';
import type { Oklch } from 'culori';
import type { TransformedToken } from 'style-dictionary/types';

import { resolvedTokens } from './build-tokens.ts';
import {
  aliasPath,
  expectRecord,
  parseColor,
  parseStringArray,
  parseUnitValue,
  round3,
} from './dtcg.ts';
import { RESOLVER_FILE } from './paths.ts';
import { loadResolver } from './resolver.ts';

const HEADER =
  'Generated by packages/tokens/scripts/build.ts from contour.resolver.json. Do not edit.';

/** The easing curves Soundor animates with. */
export type SoundorEasing = 'linear' | 'ease' | 'ease-in' | 'ease-out' | 'ease-in-out';

/** Soundor has no `cubic-bezier()`: each curve maps to the named easing closest to it. */
export const NAMED_EASING: Readonly<Record<string, SoundorEasing>> = {
  'base.easing.standard': 'ease-in-out',
  'base.easing.out': 'ease-out',
  'base.easing.in': 'ease-in',
};

/** Group of tokens that is internal to the package, as in `vars`. */
const INTERNAL_GROUP = 'base';

/** Token types without a Soundor equivalent. */
const LEFT_OUT = new Set(['shadow']);

/** A value printed as TypeScript, and the type of its leaf in `SoundorTokens`. */
interface Leaf {
  readonly value: string;
  readonly type: string;
}

const where = (token: TransformedToken): string => token.path.join('.');

const valueOf = (token: TransformedToken): unknown => {
  const value: unknown = token.$value;
  return value;
};

/** DTCG oklch color -> `#rrggbb`, or `#rrggbbaa` with an alpha. */
function hexColor(value: unknown, what: string): string {
  const { colorSpace, components, alpha } = parseColor(value, what);
  if (colorSpace !== 'oklch') {
    throw new TypeError(`${what}: only oklch colors are supported (got ${colorSpace}).`);
  }
  // `none` behaves as 0 when a color is converted.
  const [l = 0, c = 0, h = 0] = components.map((component) =>
    component === 'none' ? 0 : component,
  );
  const color: Oklch = { mode: 'oklch', l, c, h, alpha };
  return alpha === 1 ? formatHex(color) : formatHex8(color);
}

/** A length or a duration in the unit Soundor counts in, as a plain number. */
function amount(value: unknown, unit: 'px' | 'ms', what: string): number {
  const parsed = parseUnitValue(value, what);
  if (parsed.unit !== unit) {
    throw new TypeError(`${what}: expected ${unit}, got ${parsed.unit}.`);
  }
  return parsed.value;
}

function leafOf(token: TransformedToken): Leaf {
  const value = valueOf(token);
  const what = where(token);
  switch (token.$type ?? '') {
    case 'color': {
      return { value: `'${hexColor(value, what)}'`, type: 'string' };
    }
    case 'dimension': {
      return { value: String(amount(value, 'px', what)), type: 'number' };
    }
    case 'number': {
      if (typeof value !== 'number') {
        throw new TypeError(`${what}: expected a number.`);
      }
      return { value: String(value), type: 'number' };
    }
    case 'typography': {
      const parts = expectRecord(value, what);
      const fontSize = amount(parts['fontSize'], 'px', `${what}.fontSize`);
      const { fontWeight, lineHeight } = parts;
      if (typeof fontWeight !== 'number' || typeof lineHeight !== 'number') {
        throw new TypeError(`${what}: expected a numeric fontWeight and lineHeight.`);
      }
      // `fontFamily` takes one family: the first of the stack.
      const [family] = parseStringArray(parts['fontFamily'], `${what}.fontFamily`);
      const style = [
        `fontFamily: '${String(family)}'`,
        `fontSize: ${fontSize}`,
        `fontWeight: ${fontWeight}`,
        // Soundor counts the line height in px, CSS as a multiple of the font size.
        `lineHeight: ${round3(fontSize * lineHeight)}`,
        `letterSpacing: ${amount(parts['letterSpacing'], 'px', `${what}.letterSpacing`)}`,
      ];
      return { value: `{ ${style.join(', ')} }`, type: 'SoundorTextStyle' };
    }
    case 'transition': {
      const parts = expectRecord(value, what);
      const original: unknown = token.original.$value;
      const curve = aliasPath(expectRecord(original, what)['timingFunction'])?.join('.');
      const easing = curve === undefined ? undefined : NAMED_EASING[curve];
      if (easing === undefined) {
        throw new TypeError(`${what}: timingFunction must reference a curve in NAMED_EASING.`);
      }
      const transition = [
        `duration: ${amount(parts['duration'], 'ms', `${what}.duration`)}`,
        `easing: '${easing}'`,
        `delay: ${amount(parts['delay'], 'ms', `${what}.delay`)}`,
      ];
      return { value: `{ ${transition.join(', ')} }`, type: 'SoundorTransition' };
    }
    default: {
      throw new Error(`${what}: $type "${String(token.$type)}" has no Soundor value yet.`);
    }
  }
}

interface Node {
  readonly children: Map<string, Node>;
  leaf?: Leaf;
  description?: string;
}

const newNode = (): Node => ({ children: new Map() });

function treeOf(tokens: readonly TransformedToken[]): Node {
  const root = newNode();
  for (const token of tokens) {
    if (token.path[0] === INTERNAL_GROUP || LEFT_OUT.has(token.$type ?? '')) {
      continue;
    }
    let node = root;
    for (const key of token.path) {
      let child = node.children.get(key);
      if (child === undefined) {
        child = newNode();
        node.children.set(key, child);
      }
      node = child;
    }
    node.leaf = leafOf(token);
    if (token.$description !== undefined) {
      node.description = token.$description;
    }
  }
  return root;
}

const propertyName = (key: string): string => (/^[A-Za-z_$][\w$]*$/u.test(key) ? key : `'${key}'`);

const comment = (pad: string, text: string): string =>
  `${pad}/** ${text.replaceAll('*/', String.raw`*\/`)} */`;

function renderType(node: Node, depth: number, lines: string[]): void {
  const pad = '  '.repeat(depth);
  for (const [key, child] of node.children) {
    if (child.description !== undefined) {
      lines.push(comment(pad, child.description));
    }
    if (child.leaf === undefined) {
      lines.push(`${pad}readonly ${propertyName(key)}: {`);
      renderType(child, depth + 1, lines);
      lines.push(`${pad}};`);
    } else {
      lines.push(`${pad}readonly ${propertyName(key)}: ${child.leaf.type};`);
    }
  }
}

function renderValues(node: Node, depth: number, lines: string[]): void {
  const pad = '  '.repeat(depth);
  for (const [key, child] of node.children) {
    if (child.leaf === undefined) {
      lines.push(`${pad}${propertyName(key)}: {`);
      renderValues(child, depth + 1, lines);
      lines.push(`${pad}},`);
    } else {
      lines.push(`${pad}${propertyName(key)}: ${child.leaf.value},`);
    }
  }
}

/** Keys of a tree, for the check that every theme has the same tokens. */
function shapeOf(node: Node): string {
  return [...node.children]
    .map(([key, child]) => (child.leaf === undefined ? `${key}{${shapeOf(child)}}` : key))
    .join();
}

/** Build `src/generated/soundor.ts` in memory (used by the CLI and the freshness test). */
export async function buildSoundorTokens(resolverFile: string = RESOLVER_FILE): Promise<string> {
  const resolver = loadResolver(resolverFile);
  // The default theme first, as in the CSS.
  const contexts = [
    resolver.defaultContext,
    ...resolver.contexts.filter((context) => context !== resolver.defaultContext),
  ];
  const trees = await Promise.all(
    contexts.map(async (context) => {
      const tree = treeOf(await resolvedTokens(context, resolverFile));
      return [context, tree] as const;
    }),
  );
  const [defaults] = trees;
  if (defaults === undefined) {
    throw new Error(`${resolverFile}: no theme contexts.`);
  }
  const [defaultContext, defaultTree] = defaults;
  for (const [context, tree] of trees) {
    if (shapeOf(tree) !== shapeOf(defaultTree)) {
      throw new Error(`Theme "${context}" must define the same tokens as "${defaultContext}".`);
    }
  }
  const lines = [
    `// ${HEADER}`,
    '',
    "import type { Theme } from './vars.ts';",
    '',
    '/** The easing curves Soundor animates with. */',
    "export type SoundorEasing = 'linear' | 'ease' | 'ease-in' | 'ease-out' | 'ease-in-out';",
    '',
    '/** A text style as the style of a Soundor `Text`: one font family, sizes in px. */',
    'export interface SoundorTextStyle {',
    '  /** The first family of the stack: Soundor takes one. */',
    '  readonly fontFamily: string;',
    '  readonly fontSize: number;',
    '  readonly fontWeight: number;',
    '  /** In px, where CSS takes a multiple of the font size. */',
    '  readonly lineHeight: number;',
    '  readonly letterSpacing: number;',
    '}',
    '',
    '/** A transition as Soundor animates it: durations in ms, the named easing closest to the curve. */',
    'export interface SoundorTransition {',
    '  readonly duration: number;',
    '  readonly easing: SoundorEasing;',
    '  readonly delay: number;',
    '}',
    '',
    '/**',
    ' * The semantic tokens with their values for Soundor styles: colors in hex, lengths in px and',
    ' * durations in ms as numbers. Shadows have no Soundor equivalent and are left out.',
    ' */',
    'export interface SoundorTokens {',
  ];
  renderType(defaultTree, 1, lines);
  lines.push(
    '}',
    '',
    '/** The values of every token in each theme. */',
    'export const soundorTokens: Readonly<Record<Theme, SoundorTokens>> = {',
  );
  for (const [context, tree] of trees) {
    lines.push(`  ${propertyName(context)}: {`);
    renderValues(tree, 2, lines);
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}
