/**
 * Style Dictionary build for contour-ui tokens.
 *
 * - One Style Dictionary instance per theme context of `contour.resolver.json`
 *   parses the DTCG sources, merges them in resolution order, resolves and
 *   validates aliases and transforms primitive values to CSS.
 * - The results are printed into one `tokens.css` (default theme on `:root` and
 *   `[data-theme="<default>"]`, other themes only redeclare what differs), a
 *   typed `vars.ts` with `var(--ct-…)` references to the semantic tokens, and
 *   `docs.json` with every custom property's value per theme (Storybook tables).
 *
 * Aliases are printed as `var(--ct-…)` references, so semantic roles stay
 * linked to the base palette in the CSS output.
 */
import path from 'node:path';

import StyleDictionary from 'style-dictionary';
import { transformTypes } from 'style-dictionary/enums';
import type { TransformedToken, Transform } from 'style-dictionary/types';

import {
  aliasPath,
  cssColor,
  cssCubicBezier,
  cssFontFamily,
  cssPlain,
  cssUnitValue,
  expectRecord,
} from './dtcg.ts';
import { cssVar, cssVarName } from './naming.ts';
import { RESOLVER_FILE } from './paths.ts';
import { loadResolver } from './resolver.ts';
import type { ThemeResolver } from './resolver.ts';

const HEADER =
  'Generated by packages/tokens/scripts/build.ts from contour.resolver.json. Do not edit.';

/** Group of tokens that is internal to the package: emitted in CSS, not exported to TS. */
const INTERNAL_GROUP = 'base';

type Formatter = (value: unknown, what: string) => string;

/** Typography sub-values become separate custom properties, in this order. */
const TYPOGRAPHY: ReadonlyArray<readonly [string, Formatter]> = [
  ['fontFamily', cssFontFamily],
  ['fontSize', cssUnitValue],
  ['fontWeight', cssPlain],
  ['lineHeight', cssPlain],
  ['letterSpacing', cssUnitValue],
];

/** Transition sub-values in CSS `transition` shorthand order: duration, timing function, delay. */
const TRANSITION: ReadonlyArray<readonly [string, Formatter]> = [
  ['duration', cssUnitValue],
  ['timingFunction', cssCubicBezier],
  ['delay', cssUnitValue],
];

/**
 * Shadow layer sub-values in CSS `box-shadow` order, after the optional `inset`.
 * Printed here like the other composites rather than with Style Dictionary's
 * `shadow/css/shorthand`, which works on resolved values: aliases stay `var()`
 * references and colors keep the oklch format.
 */
const SHADOW: ReadonlyArray<readonly [string, Formatter]> = [
  ['offsetX', cssUnitValue],
  ['offsetY', cssUnitValue],
  ['blur', cssUnitValue],
  ['spread', cssUnitValue],
  ['color', cssColor],
];

const what = (token: TransformedToken): string => `${token.path.join('.')} (${token.filePath})`;

const valueOf = (token: TransformedToken): unknown => {
  const value: unknown = token.$value;
  return value;
};

const ofType =
  (...types: string[]) =>
  (token: TransformedToken): boolean =>
    types.includes(token.$type ?? '');

type Transforms = Record<string, Omit<Transform, 'name'>>;

const NAME_TRANSFORMS: Transforms = {
  'contour/name': {
    type: transformTypes.name,
    transform: (token) => cssVarName(token.path).slice(2),
  },
};

/** Primitive value transforms for DTCG 2025.10 values (composites are printed below). */
const TRANSFORMS: Transforms = {
  ...NAME_TRANSFORMS,
  'contour/color': {
    type: transformTypes.value,
    filter: ofType('color'),
    transform: (token) => cssColor(valueOf(token), what(token)),
  },
  'contour/unit-value': {
    type: transformTypes.value,
    filter: ofType('dimension', 'duration'),
    transform: (token) => cssUnitValue(valueOf(token), what(token)),
  },
  'contour/cubic-bezier': {
    type: transformTypes.value,
    filter: ofType('cubicBezier'),
    transform: (token) => cssCubicBezier(valueOf(token), what(token)),
  },
  'contour/font-family': {
    type: transformTypes.value,
    filter: ofType('fontFamily'),
    transform: (token) => cssFontFamily(valueOf(token), what(token)),
  },
};

async function contextTokens(
  resolver: ThemeResolver,
  context: string,
  transforms: Transforms = TRANSFORMS,
): Promise<TransformedToken[]> {
  const { include, source } = resolver.files(context);
  const sd = new StyleDictionary({
    include,
    source,
    // Collisions and other warnings fail the build; success logs stay quiet.
    log: { warnings: 'error', verbosity: 'silent' },
    hooks: { transforms },
    platforms: {
      css: { transforms: Object.keys(transforms) },
    },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens;
}

/**
 * Every token of one theme context with aliases resolved and values left as
 * DTCG data (color objects, `{ value, unit }` dimensions…), for checks of the
 * values themselves rather than of their CSS.
 */
export async function resolvedTokens(
  context: string,
  resolverFile: string = RESOLVER_FILE,
): Promise<TransformedToken[]> {
  const tokens = await contextTokens(loadResolver(resolverFile), context, NAME_TRANSFORMS);
  return tokens;
}

interface Declaration {
  readonly name: string;
  readonly value: string;
  /** Path below the token for composite sub-values (`['fontSize']`), empty otherwise. */
  readonly key: readonly string[];
}

/** Print a value: aliases as `var(--ct-…)`, literals with `format`. */
function printValue(value: unknown, format: Formatter, where: string): string {
  const alias = aliasPath(value);
  return alias === undefined ? format(value, where) : cssVar(alias);
}

/**
 * `--ct-text-<style>`: CSS `font` shorthand built from the style's own custom
 * properties (`font: var(--ct-text-label)`). `letter-spacing` is not part of the
 * `font` shorthand and stays a separate property.
 */
function fontShorthand(
  token: TransformedToken,
  alias: string[] | undefined,
  properties: readonly Declaration[],
): Declaration[] {
  const name = cssVarName(token.path);
  if (alias !== undefined) {
    return [{ name, value: cssVar(alias), key: ['font'] }];
  }
  const ref = (key: string): string | undefined =>
    properties.some((property) => property.key[0] === key)
      ? cssVar([...token.path, key])
      : undefined;
  const [weight, size, lineHeight, family] = [
    ref('fontWeight'),
    ref('fontSize'),
    ref('lineHeight'),
    ref('fontFamily'),
  ];
  if (size === undefined || family === undefined) {
    return [];
  }
  const sizeAndLineHeight = lineHeight === undefined ? size : `${size}/${lineHeight}`;
  const value = [weight, sizeAndLineHeight, family].filter((part) => part !== undefined).join(' ');
  return [{ name, value, key: ['font'] }];
}

/** One `box-shadow` layer: a shadow object, or an alias of a whole shadow token. */
function shadowLayer(layer: unknown, where: string): string {
  const alias = aliasPath(layer);
  if (alias !== undefined) {
    return cssVar(alias);
  }
  const parts = expectRecord(layer, where);
  const inset = parts['inset'] ?? false;
  if (typeof inset !== 'boolean') {
    throw new TypeError(`${where}.inset: expected a boolean.`);
  }
  const values = SHADOW.map(([key, format]) => printValue(parts[key], format, `${where}.${key}`));
  return (inset ? ['inset', ...values] : values).join(' ');
}

function declarationsOf(token: TransformedToken): Declaration[] {
  const original: unknown = token.original.$value;
  const alias = aliasPath(original);

  switch (token.$type ?? '') {
    case 'typography': {
      const parts = alias === undefined ? expectRecord(original, what(token)) : undefined;
      const properties = TYPOGRAPHY.flatMap(([key, format]) => {
        const name = cssVarName([...token.path, key]);
        if (alias !== undefined) {
          return [{ name, value: cssVar([...alias, key]), key: [key] }];
        }
        const part = parts?.[key];
        return part === undefined
          ? []
          : [{ name, value: printValue(part, format, `${what(token)}.${key}`), key: [key] }];
      });
      return [...fontShorthand(token, alias, properties), ...properties];
    }
    case 'transition': {
      if (alias !== undefined) {
        return [{ name: cssVarName(token.path), value: cssVar(alias), key: [] }];
      }
      const parts = expectRecord(original, what(token));
      const value = TRANSITION.map(([key, format]) =>
        printValue(parts[key], format, `${what(token)}.${key}`),
      ).join(' ');
      return [{ name: cssVarName(token.path), value, key: [] }];
    }
    case 'shadow': {
      // One layer or a list of layers; `box-shadow` takes a comma-separated list.
      const layers: unknown[] = Array.isArray(original) ? original : [original];
      const value =
        alias === undefined
          ? layers.map((layer, index) => shadowLayer(layer, `${what(token)}[${index}]`)).join(', ')
          : cssVar(alias);
      return [{ name: cssVarName(token.path), value, key: [] }];
    }
    case 'color':
    case 'dimension':
    case 'duration':
    case 'cubicBezier':
    case 'fontFamily':
    case 'fontWeight':
    case 'number': {
      const value = alias === undefined ? cssPlain(valueOf(token), what(token)) : cssVar(alias);
      return [{ name: cssVarName(token.path), value, key: [] }];
    }
    default: {
      throw new Error(`${what(token)}: $type "${String(token.$type)}" is not supported yet.`);
    }
  }
}

interface ContextOutput {
  readonly context: string;
  readonly tokens: TransformedToken[];
  readonly declarations: Map<string, Declaration[]>;
  readonly resolved: Map<string, string>;
}

function contextOutput(context: string, tokens: TransformedToken[]): ContextOutput {
  const declarations = new Map<string, Declaration[]>();
  const resolved = new Map<string, string>();
  const seen = new Map<string, string>();
  for (const token of tokens) {
    const tokenDeclarations = declarationsOf(token);
    for (const { name } of tokenDeclarations) {
      const previous = seen.get(name);
      if (previous !== undefined) {
        throw new Error(`${name} is produced by both ${previous} and ${token.path.join('.')}.`);
      }
      seen.set(name, token.path.join('.'));
    }
    declarations.set(token.name, tokenDeclarations);
    resolved.set(token.name, JSON.stringify(valueOf(token)));
  }
  return { context, tokens, declarations, resolved };
}

function cssBlock(selector: string, context: string, declarations: Declaration[]): string {
  const colorScheme =
    context === 'dark' || context === 'light' ? [`color-scheme: ${context};`] : [];
  const lines = [...colorScheme, ...declarations.map(({ name, value }) => `${name}: ${value};`)];
  return `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}\n`;
}

function printCss(resolver: ThemeResolver, outputs: ContextOutput[]): string {
  const attribute = `data-${resolver.modifier}`;
  const [defaults, ...others] = outputs;
  if (defaults === undefined) {
    throw new Error('No theme contexts to build.');
  }
  const blocks = [
    cssBlock(
      `:root,\n[${attribute}="${defaults.context}"]`,
      defaults.context,
      [...defaults.declarations.values()].flat(),
    ),
    ...others.map((output) => {
      // Redeclare every token whose resolved value differs from the default theme,
      // including aliases of theme tokens: a custom property inherits its computed
      // value, so an alias declared only on :root would keep the default value.
      const changed = [...output.declarations].filter(
        ([name]) => output.resolved.get(name) !== defaults.resolved.get(name),
      );
      return cssBlock(
        `[${attribute}="${output.context}"]`,
        output.context,
        changed.flatMap(([, declarations]) => declarations),
      );
    }),
  ];
  return `/* ${HEADER} */\n\n${blocks.join('\n')}`;
}

interface VarNode {
  readonly children: Map<string, VarNode>;
  value?: string;
  description?: string;
}

const newNode = (): VarNode => ({ children: new Map() });

function nodeAt(root: VarNode, keys: readonly string[]): VarNode {
  let node = root;
  for (const key of keys) {
    let child = node.children.get(key);
    if (child === undefined) {
      child = newNode();
      node.children.set(key, child);
    }
    node = child;
  }
  return node;
}

function renderVars(node: VarNode, depth: number): string[] {
  const pad = '  '.repeat(depth);
  const lines: string[] = [];
  for (const [key, child] of node.children) {
    const property = /^[A-Za-z_$][\w$]*$/u.test(key) ? key : `'${key}'`;
    if (child.description !== undefined) {
      lines.push(`${pad}/** ${child.description.replaceAll('*/', String.raw`*\/`)} */`);
    }
    if (child.value === undefined) {
      lines.push(`${pad}${property}: {`, ...renderVars(child, depth + 1), `${pad}},`);
    } else {
      lines.push(`${pad}${property}: '${child.value}',`);
    }
  }
  return lines;
}

function printTs(resolver: ThemeResolver, defaults: ContextOutput): string {
  const root = newNode();
  for (const token of defaults.tokens) {
    if (token.path[0] === INTERNAL_GROUP) {
      continue;
    }
    const node = nodeAt(root, token.path);
    if (token.$description !== undefined) {
      node.description = token.$description;
    }
    for (const { name, key } of defaults.declarations.get(token.name) ?? []) {
      nodeAt(node, key).value = `var(${name})`;
    }
  }
  const themes = resolver.contexts.map((context) => `'${context}'`).join(', ');
  return [
    `// ${HEADER}`,
    '',
    '/**',
    ' * `var(--ct-…)` references for every semantic token. Values follow the active',
    ` * theme through CSS; base tokens are internal and not exported.`,
    ' */',
    'export const vars = {',
    ...renderVars(root, 1),
    '} as const;',
    '',
    `/** Theme contexts from ${path.basename(RESOLVER_FILE)}. */`,
    `export const themes = [${themes}] as const;`,
    '',
    'export type Theme = (typeof themes)[number];',
    '',
    `export const defaultTheme: Theme = '${resolver.defaultContext}';`,
    '',
    `/** Attribute that switches the theme of any subtree, e.g. \`data-${resolver.modifier}="${resolver.defaultContext}"\`. */`,
    `export const themeAttribute = 'data-${resolver.modifier}';`,
    '',
  ].join('\n');
}

/** A `var(--…)` reference inside a CSS value; the whole value when it is an alias. */
const VAR_REFERENCE = /var\((--[\w-]+)\)/gu;
const ALIAS = /^var\((--[\w-]+)\)$/u;

/** Substitute `var()` references recursively, the way the browser computes a custom property. */
function resolveVars(value: string, declared: ReadonlyMap<string, string>): string {
  return value.replaceAll(VAR_REFERENCE, (reference: string, name: string) => {
    const target = declared.get(name);
    if (target === undefined) {
      throw new Error(`${reference} does not match any declaration.`);
    }
    return resolveVars(target, declared);
  });
}

interface ThemeValue {
  /** Fully resolved CSS value. */
  readonly value: string;
  /** Custom property this one is an alias of, `null` for literals and shorthands. */
  readonly alias: string | null;
}

interface TokenDoc {
  /** Custom property, e.g. `--ct-text-label-font-size`. */
  readonly name: string;
  /** DTCG path of the token it comes from, e.g. `text.label`. */
  readonly token: string;
  readonly type: string;
  /** Composite sub-value (`font` shorthand, `fontSize`…), `null` for a whole token. */
  readonly part: string | null;
  readonly description: string | null;
  readonly themes: Readonly<Record<string, ThemeValue>>;
}

function themeValue(name: string, values: ReadonlyMap<string, string>): ThemeValue {
  const value = values.get(name);
  if (value === undefined) {
    throw new Error(`${name} is missing in a theme.`);
  }
  return { value: resolveVars(value, values), alias: ALIAS.exec(value)?.[1] ?? null };
}

/** `docs.json`: every custom property of `tokens.css`, one per line, with its value per theme. */
function printDocs(outputs: readonly ContextOutput[]): string {
  const [defaults] = outputs;
  if (defaults === undefined) {
    throw new Error('No theme contexts to build.');
  }
  const declared = outputs.map(({ context, declarations }) => ({
    context,
    values: new Map(
      [...declarations.values()].flat().map(({ name, value }): [string, string] => [name, value]),
    ),
  }));
  const docs = defaults.tokens.flatMap((token) =>
    (defaults.declarations.get(token.name) ?? []).map(({ name, key }): TokenDoc => ({
      name,
      token: token.path.join('.'),
      type: token.$type ?? '',
      part: key.length > 0 ? key.join('.') : null,
      description: token.$description ?? null,
      themes: Object.fromEntries(
        declared.map(({ context, values }) => [context, themeValue(name, values)]),
      ),
    })),
  );
  const lines = docs.map((doc) => `    ${JSON.stringify(doc)}`).join(',\n');
  return `{\n  "$description": ${JSON.stringify(HEADER)},\n  "tokens": [\n${lines}\n  ]\n}\n`;
}

export interface TokenBuild {
  readonly css: string;
  readonly ts: string;
  readonly docs: string;
}

/** Build `tokens.css`, `vars.ts` and `docs.json` in memory (used by the CLI and the freshness test). */
export async function buildTokens(resolverFile: string = RESOLVER_FILE): Promise<TokenBuild> {
  const resolver = loadResolver(resolverFile);
  // Default context first: it is the base layer of the CSS.
  const contexts = [
    resolver.defaultContext,
    ...resolver.contexts.filter((context) => context !== resolver.defaultContext),
  ];
  const results = await Promise.all(
    contexts.map(async (context) => contextOutput(context, await contextTokens(resolver, context))),
  );

  const [defaults] = results;
  if (defaults === undefined) {
    throw new Error(`${resolverFile}: no theme contexts.`);
  }
  const expected = [...defaults.declarations.keys()].toSorted().join();
  for (const output of results) {
    if ([...output.declarations.keys()].toSorted().join() !== expected) {
      throw new Error(
        `Theme "${output.context}" must define the same tokens as "${defaults.context}".`,
      );
    }
  }

  return {
    css: printCss(resolver, results),
    ts: printTs(resolver, defaults),
    docs: printDocs(results),
  };
}
