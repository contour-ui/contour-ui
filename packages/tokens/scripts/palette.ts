/**
 * Base palette in DTCG 2025.10 format (`src/base/color.tokens.json`).
 * Every chromatic hue shares one lightness curve, so `blue.500` and `red.500`
 * have the same perceived lightness and contrast pairs transfer between hues.
 * Every color is inside sRGB, so it converts to hex without clipping.
 */
import { displayable, formatHex, oklch, toGamut } from 'culori';

import { round3 } from './dtcg.ts';
import type { JsonRecord } from './dtcg.ts';

/** Shared lightness curve (OKLCH L) for all hues: [stop, L]. */
const STOPS: ReadonlyArray<readonly [number, number]> = [
  [50, 0.97],
  [100, 0.93],
  [200, 0.87],
  [300, 0.79],
  [400, 0.7],
  [500, 0.62],
  [600, 0.54],
  [700, 0.46],
  [800, 0.37],
  [900, 0.28],
  [950, 0.21],
];

/** Neutral gets extra ends: pure-ish white for light surfaces and a deep stop for dark plugin canvases. */
const NEUTRAL_EXTRA: ReadonlyArray<readonly [number, number]> = [
  [0, 1],
  [975, 0.165],
];

interface Hue {
  /** OKLCH hue angle. */
  readonly hue: number;
  /** Peak chroma at mid lightness. */
  readonly chroma: number;
  /** Keep chroma constant (neutral). */
  readonly flat: boolean;
}

const HUES: ReadonlyArray<readonly [string, Hue]> = [
  ['neutral', { hue: 255, chroma: 0.008, flat: true }],
  ['blue', { hue: 255, chroma: 0.17, flat: false }],
  ['red', { hue: 25, chroma: 0.19, flat: false }],
  ['green', { hue: 150, chroma: 0.16, flat: false }],
  ['yellow', { hue: 85, chroma: 0.16, flat: false }],
];

/**
 * Chroma falls off toward very light and very dark stops, where high chroma is
 * out of gamut and looks muddy anyway.
 */
function chromaAt(lightness: number, { chroma, flat }: Hue): number {
  if (flat) {
    return chroma;
  }
  const t = (lightness - 0.62) / 0.42;
  return Math.max(chroma * (1 - t * t), chroma * 0.15);
}

/** CSS Color 4 gamut mapping into sRGB: may shift lightness and hue a little to keep chroma. */
const toGamutSrgb = toGamut('rgb', 'oklch');

/**
 * The gamut-mapped color, written with its own coordinates rather than the
 * requested hue, so the oklch value and the hex fallback are the same sRGB
 * color. Rounding to 3 decimals can push a color on the gamut edge slightly
 * outside; chroma then steps down until it is displayable.
 */
function colorToken(lightness: number, chroma: number, hue: number): JsonRecord {
  const mapped = oklch(toGamutSrgb({ mode: 'oklch', l: lightness, c: chroma, h: hue }));
  const color = {
    mode: 'oklch' as const,
    l: round3(mapped.l),
    c: round3(mapped.c),
    h: chroma === 0 ? 0 : round3(mapped.h ?? hue),
  };
  while (color.c > 0 && !displayable(color)) {
    color.c = round3(color.c - 0.001);
  }
  return {
    $value: {
      colorSpace: 'oklch',
      components: [color.l, color.c, color.h],
      alpha: 1,
      hex: formatHex(color),
    },
  };
}

export function generatePalette(): JsonRecord {
  const color: JsonRecord = { $type: 'color' };
  for (const [name, hue] of HUES) {
    const stops = (name === 'neutral' ? [...NEUTRAL_EXTRA, ...STOPS] : [...STOPS]).toSorted(
      ([a], [b]) => a - b,
    );
    const group: JsonRecord = {};
    for (const [stop, lightness] of stops) {
      const chroma = name === 'neutral' && stop === 0 ? 0 : chromaAt(lightness, hue);
      group[String(stop)] = colorToken(lightness, chroma, hue.hue);
    }
    color[name] = group;
  }
  return {
    $schema: 'https://www.designtokens.org/schemas/2025.10/format.json',
    base: {
      $description: 'Base palette. Generated by scripts/generate.ts — do not edit by hand.',
      color,
    },
  };
}
