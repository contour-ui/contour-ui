/**
 * Paths of the committed font files and the text of the files generated from the sources:
 * `src/fonts.css` (the `@font-face` rules of the WOFF2 files, from the CSS of each Fontsource
 * weight) and `src/generated/faces.ts` (the TTF faces).
 */
import path from 'node:path';

import { SOURCES, WEIGHTS, ttfName } from './sources.ts';
import type { FontSource, FontWeight } from './sources.ts';

export const PACKAGE_DIR = path.resolve(import.meta.dirname, '..');
export const SRC_DIR = path.join(PACKAGE_DIR, 'src');
export const WOFF2_DIR = path.join(SRC_DIR, 'woff2');
export const TTF_DIR = path.join(SRC_DIR, 'ttf');
export const LICENSES_DIR = path.join(SRC_DIR, 'licenses');
export const CSS_FILE = path.join(SRC_DIR, 'fonts.css');
export const FACES_FILE = path.join(SRC_DIR, 'generated', 'faces.ts');

/** The license of a family, copied unmodified from its Fontsource package. */
export const licenseName = ({ id }: FontSource): string => `${id}.txt`;

/** One `@font-face` of a WOFF2 subset. */
export interface WebFace {
  /** File name without extension: `ibm-plex-sans-latin-400-normal`. */
  readonly name: string;
  readonly family: string;
  readonly weight: FontWeight;
  readonly unicodeRange: string;
}

const FACE_RULE = /\/\* (?<name>[\w-]+) \*\/\s*@font-face \{(?<body>[^}]*)\}/gu;

function declaration(body: string, property: string, name: string): string {
  const match = new RegExp(String.raw`(?:^|;)\s*${property}:\s*(?<value>[^;]+);`, 'u').exec(body);
  const value = match?.groups?.['value'];
  if (value === undefined) {
    throw new Error(`${name}: no ${property} in the Fontsource CSS`);
  }
  return value.trim();
}

/** The faces of one weight from Fontsource's `<weight>.css`, every subset in its order. */
export function parseWebFaces(source: FontSource, weight: FontWeight, css: string): WebFace[] {
  const faces = [...css.matchAll(FACE_RULE)].map(({ groups }): WebFace => {
    const name = groups?.['name'] ?? '';
    const body = groups?.['body'] ?? '';
    const expected = {
      'font-family': `'${source.family}'`,
      'font-style': 'normal',
      'font-display': 'swap',
      'font-weight': String(weight),
    };
    for (const [property, value] of Object.entries(expected)) {
      const actual = declaration(body, property, name);
      if (actual !== value) {
        throw new Error(`${name}: ${property} is ${actual}, expected ${value}`);
      }
    }
    if (!declaration(body, 'src', name).startsWith(`url(./files/${name}.woff2) format('woff2')`)) {
      throw new Error(`${name}: src does not start with ./files/${name}.woff2`);
    }
    return {
      name,
      family: source.family,
      weight,
      unicodeRange: declaration(body, 'unicode-range', name),
    };
  });
  if (faces.length === 0) {
    throw new Error(`${source.id} ${weight}: no @font-face in the Fontsource CSS`);
  }
  return faces;
}

export function fontsCss(faces: readonly WebFace[]): string {
  const header = [
    '/*',
    ' * Generated by packages/fonts/scripts/build.ts from Fontsource. Do not edit.',
    ' *',
    ` * Font faces for ${SOURCES.map(({ family }) => family).join(' and ')} (SIL OFL 1.1, see licenses/),`,
    ` * one per weight (${WEIGHTS.join(', ')}). Each weight covers several scripts via unicode-range;`,
    ' * browsers fetch only the subsets a page uses. Import once, next to tokens.css.',
    ' */',
  ];
  const rules = faces.map((face) =>
    [
      `/* ${face.name} */`,
      '@font-face {',
      `  font-family: '${face.family}';`,
      '  font-style: normal;',
      '  font-display: swap;',
      `  font-weight: ${face.weight};`,
      `  src: url('./woff2/${face.name}.woff2') format('woff2');`,
      `  unicode-range: ${face.unicodeRange};`,
      '}',
    ].join('\n'),
  );
  return `${[header.join('\n'), ...rules].join('\n\n')}\n`;
}

export function facesModule(): string {
  const entries = SOURCES.flatMap((source) =>
    WEIGHTS.map((weight) =>
      [
        '  {',
        `    family: '${source.family}',`,
        `    weight: ${weight},`,
        "    style: 'normal',",
        `    file: 'ttf/${ttfName(source, weight)}',`,
        '  },',
      ].join('\n'),
    ),
  );
  return [
    '// Generated by packages/fonts/scripts/build.ts from scripts/sources.ts. Do not edit.',
    "import type { FontFaceData } from '../font-face-data.ts';",
    '',
    '/** The static TTF faces (Latin), one file per family and weight. */',
    'export const fontFaces: readonly FontFaceData[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}
